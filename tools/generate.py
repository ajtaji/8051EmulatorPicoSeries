def next_op(target, c):
    t = TARGETS[target]
    out = ['CompilerIf #M51_ASM_TAIL = 1', '  CompilerIf #M51_TIMING = 1']
    out += ['    ' + l for l in t['budget_asm'](c)]
    out += ['  CompilerElse']
    out += ['    ' + l for l in t['budget_asm'](1)]
    out += ['  CompilerEndIf']
    out += ['  ' + l for l in t['dispatch_asm']]
    out += ['CompilerElse',
            '  CompilerIf #M51_TIMING = 1',
            f'    M51Left = M51Left - {c}',
            '  CompilerElse',
            '    M51Left = M51Left - 1',
            '  CompilerEndIf',
            '  If M51Left <= 0',
            '    Goto Done',
            '  EndIf',
            '  M51Tmp = M51Code(M51PC)',
            '  ' + INC_PC,
            '  Goto M51Dispatch(M51Tmp)',
            'CompilerEndIf']
    return out


def first_dispatch(target):
    t = TARGETS[target]
    return (['CompilerIf #M51_ASM_TAIL = 1'] + ['  ' + l for l in t['dispatch_asm']] +
            ['CompilerElse', '  M51Tmp = M51Code(M51PC)', '  ' + INC_PC, '  Goto M51Dispatch(M51Tmp)',
             'CompilerEndIf'])


def build(target):
    t = TARGETS[target]
    out = [HEADER.replace('@@TABLE_GLOBAL@@', t['table_global']).replace('@@RESERVE@@', t['reserve'])]
    out.append('; Executes whole instructions while the budget lasts. Each handler ends')
    out.append('; in its own copy of the dispatch tail; there is no call per instruction.')
    out.append('ProcedureRAM.i M51Slice(n.i)')
    out.append('  If M51Ready = 0')
    out.append('    For M51InitIndex = 0 To 255')
    out.append('      M51Dispatch(M51InitIndex) = ?Illegal')
    out.append('    Next')
    for code in sorted(ops):
        out.append(f'    M51Dispatch(${code:02X}) = ?Op{code:02X}')
    out.append('    M51Ready = 1')
    out.append('  EndIf')
    if t['table_init']:
        out.append(t['table_init'].rstrip('\n'))
    out.append('  M51Budget = n')
    out.append('  M51Left = n')
    out.append('  M51Stolen = 0')
    out += ['  ' + l for l in first_dispatch(target)]
    out.append('Illegal:')
    out.append('  ; $A5 is not an instruction: stop on it, uncounted, PC at the byte.')
    out.append('  M51PC = (M51PC - 1) & $FFFF')
    out.append('  M51BadOpcode = M51Code(M51PC)')
    out.append('  M51Stopped = 1')
    out.append('  Goto Done')
    for code in sorted(ops):
        text, cycles, lines = ops[code]
        out.append(f'Op{code:02X}: ; ${code:02X} {text}, {cycles} cycle{"s" if cycles > 1 else ""}')
        tail = next_op(target, cycles)
        has_tail = False
        for l in lines:
            if l.strip() == TAIL:
                pad = l[:len(l) - len(l.lstrip())]
                out += ['  ' + pad + t for t in tail]
                has_tail = True
            else:
                out.append('  ' + l)
        if not has_tail:
            out += ['  ' + l for l in tail]
    out.append('Done:')
    out.append('  M51Res = M51Budget - M51Stolen - M51Left')
    out.append('  M51Cycles = M51Cycles + M51Res')
    out.append('  M51SliceBase = M51Cycles')
    out.append('  M51Budget = 0')
    out.append('  M51Stolen = 0')
    out.append('  M51Left = 0')
    out.append('  ProcedureReturn M51Res')
    out.append('EndProcedure')
    out.append(API)
    return '\n'.join(out) + '\n'


def cycle_table():
    return [ops[i][1] if i in ops else 0 for i in range(256)]


if __name__ == '__main__':
    # py -3 tools/generate.py [RP2040 variant]: 'pico_low' (default) or 'pico'.
    import sys
    rp2040 = sys.argv[1] if len(sys.argv) > 1 else 'pico_low'
    for target, ext in [(rp2040, 'pico'), ('pico2', 'pico2')]:
        text = build(target)
        path = ROOT / 'src' / f'mcs51.{ext}'
        path.write_text(text, newline='\n')

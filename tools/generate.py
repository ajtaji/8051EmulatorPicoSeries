op(0x10, 'JBC bit,rel', 2, fetch('M51Tmp') + [
    'If M51BitReadLatch(M51Tmp)',
    '  M51BitWrite(M51Tmp, 0)'] + ['  ' + l for l in rel_jump()] + ['Else', '  ' + INC_PC, 'EndIf'])

# Branches
op(0x80, 'SJMP rel', 2, rel_jump())
op(0x40, 'JC rel', 2, cond_jump('(M51CyX & $100) <> 0'))
op(0x50, 'JNC rel', 2, cond_jump('(M51CyX & $100) = 0'))
op(0x60, 'JZ rel', 2, cond_jump('M51A = 0'))
op(0x70, 'JNZ rel', 2, cond_jump('M51A <> 0'))
op(0x73, 'JMP @A+DPTR', 2, ['M51PC = (M51A + M51DPTR) & $FFFF'])
op(0x02, 'LJMP addr16', 2, ['M51PC = (M51Code(M51PC) << 8) | M51Code((M51PC + 1) & $FFFF)'])
op(0x12, 'LCALL addr16', 2, [
    'M51Ea = (M51Code(M51PC) << 8) | M51Code((M51PC + 1) & $FFFF)',
    'M51PC = (M51PC + 2) & $FFFF',
    'M51Push(M51PC & 255)', 'M51Push(M51PC >> 8)', 'M51PC = M51Ea'])
for page in range(8):
    op(0x01 + (page << 5), f'AJMP page{page}', 2, [
        'M51Tmp = M51Code(M51PC)',
        f'M51PC = ((M51PC + 1) & $F800) | {page << 8} | M51Tmp'])
    op(0x11 + (page << 5), f'ACALL page{page}', 2, [
        'M51Tmp = M51Code(M51PC)',
        INC_PC,
        'M51Push(M51PC & 255)', 'M51Push(M51PC >> 8)',
        f'M51PC = (M51PC & $F800) | {page << 8} | M51Tmp'])
op(0x22, 'RET', 2, ['M51Pop(M51Tmp)', 'M51Pop(M51Val)', 'M51PC = (M51Tmp << 8) | M51Val'])
op(0x32, 'RETI', 2, ['M51Pop(M51Tmp)', 'M51Pop(M51Val)', 'M51PC = (M51Tmp << 8) | M51Val',
                     'If M51IntActive & 2', '  M51IntActive = M51IntActive & 1', 'Else', '  M51IntActive = 0',
                     'EndIf',
                     '; One more instruction always runs before the next interrupt.',
                     'M51IntHold = 1', 'M51ForceExit()'])

# CJNE: CY = first < second (unsigned), branch if not equal.
op(0xB4, 'CJNE A,#imm,rel', 2, fetch('M51Val') + ['M51CyX = M51A - M51Val'] + cond_jump('M51A <> M51Val'))
op(0xB5, 'CJNE A,dir,rel', 2, fetch('M51Ea') + rd_dir('M51Val') + ['M51CyX = M51A - M51Val'] + cond_jump('M51A <> M51Val'))
for i in (0, 1):
    op(0xB6 + i, f'CJNE @R{i},#imm,rel', 2, [f'M51RdInd(M51Res, {ri(i)})'] + fetch('M51Val') +
       ['M51CyX = M51Res - M51Val'] + cond_jump('M51Res <> M51Val'))
for n in range(8):
    op(0xB8 + n, f'CJNE R{n},#imm,rel', 2, [f'M51Res = {rn(n)}'] + fetch('M51Val') +
       ['M51CyX = M51Res - M51Val'] + cond_jump('M51Res <> M51Val'))

# DJNZ
op(0xD5, 'DJNZ dir,rel', 2, fetch('M51Ea') + rd_dir('M51Val', latch=True) + ['M51Val = (M51Val - 1) & 255'] +
   wr_dir('M51Val') + cond_jump('M51Val <> 0'))
for n in range(8):
    op(0xD8 + n, f'DJNZ R{n},rel', 2, [f'M51Res = ({rn(n)} - 1) & 255', f'{rn(n)} = M51Res'] + cond_jump('M51Res <> 0'))

op(0x00, 'NOP', 1, [])

assert len(ops) == 255 and 0xA5 not in ops, len(ops)


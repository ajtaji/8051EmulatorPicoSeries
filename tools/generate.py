def bit_addr_inline(kind):
    """CLR / SETB / CPL bit: inline for the byte RAM case."""
    expr = {'clr': 'M51IRam(M51Ea) & (~(1 << (M51Tmp & 7)))',
            'setb': 'M51IRam(M51Ea) | (1 << (M51Tmp & 7))',
            'cpl': 'M51IRam(M51Ea) ! (1 << (M51Tmp & 7))'}[kind]
    other = {'clr': 'M51BitWrite(M51Tmp, 0)', 'setb': 'M51BitWrite(M51Tmp, 1)',
             'cpl': 'M51BitWrite(M51Tmp, M51BitReadLatch(M51Tmp) ! 1)'}[kind]
    return fetch('M51Tmp') + ['If M51Tmp < $80', '  M51Ea = $20 + (M51Tmp >> 3)', f'  M51IRam(M51Ea) = {expr}',
                              'Else', f'  {other}', 'EndIf']



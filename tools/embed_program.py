"""Embeds an 8051 program image for the Pico PM51 firmware.

  py -3 tools/embed_program.py <program.bin> [name]

Writes machine/pm51_program.pico and .pico2: a DataSection (label
PM51Program) and #PM51_PROGRAM_SIZE. The image loads at code address $0000.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1])
name = sys.argv[2] if len(sys.argv) > 2 else src.stem
data = src.read_bytes()
lines = [f'; Generated by tools/embed_program.py from {src.name}: the 8051 program this firmware runs.',
         f'#PM51_PROGRAM_SIZE = {len(data)}', 'DataSection', 'PM51ProgramName:',
         f'  Data.a ' + ','.join(str(b) for b in name.encode()) + ',0', 'PM51Program:']
for i in range(0, len(data), 32):
    lines.append('  Data.a ' + ','.join(f'${b:02X}' for b in data[i:i + 32]))
lines.append('EndDataSection')
for ext in ('pico', 'pico2'):
    (ROOT / 'machine' / f'pm51_program.{ext}').write_text('\n'.join(lines) + '\n', newline='\n')
print(len(data), 'bytes embedded as', name)

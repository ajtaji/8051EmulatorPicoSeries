"""Embed the test data as PureMetal DataSections (kept in flash).

tests/vectors.bin -> tests/test_data.pico / .pico2 (label Vectors)
tests/programs/*.bin -> tests/program_data.pico / .pico2 (one label per program)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TESTS = ROOT / 'tests'


def section(items):
    lines = ['; Generated by tools/embed_tests.py.', 'DataSection']
    for label, data in items:
        lines.append(label + ':')
        for start in range(0, len(data), 32):
            lines.append('  Data.a ' + ','.join(f'${x:02X}' for x in data[start:start + 32]))
    lines.append('EndDataSection')
    return '\n'.join(lines) + '\n'


def write_both(stem, text):
    for ext in ('pico', 'pico2'):
        (TESTS / f'{stem}.{ext}').write_text(text, newline='\n')


if __name__ == '__main__':
    write_both('test_data', section([('Vectors', (TESTS / 'vectors.bin').read_bytes())]))
    write_both('program_data', section([('Programs', (TESTS / 'programs.bin').read_bytes()),
                                        ('AsmData', (TESTS / 'asm_tests.bin').read_bytes())]))
    (TESTS / 'test_counts.pico').write_text((TESTS / 'vector_count.pico').read_text() +
                                            (TESTS / 'program_count.pico').read_text() +
                                            (TESTS / 'asm_count.pico').read_text(), newline='\n')
    (TESTS / 'test_counts.pico2').write_text((TESTS / 'test_counts.pico').read_text(), newline='\n')
    # The RP2350 builds include .pico2 files: their copies of the shared
    # bodies are made here, never edited by hand.
    for rel in ('tests/verify_body', 'tests/verify_main', 'src/demo_body', 'src/io'):
        (ROOT / f'{rel}.pico2').write_text((ROOT / f'{rel}.pico').read_text(), newline='\n')
    print('vectors and programs embedded; .pico2 copies refreshed')

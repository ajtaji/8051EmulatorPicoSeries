"""The PM51 board's character font: ASCII 32-126 as 8x8 glyphs.

Source: font8x8_basic.h by Daniel Hepper (public domain; the IBM VGA glyphs),
from https://github.com/dhepper/font8x8. One byte per glyph row, top row
first; bit 0 is the LEFTMOST pixel. Writes machine/pm51_font.pico and .pico2
(a DataSection, label PM51Font, glyph for code c at (c - 32) * 8).

  py -3 tools/make_font.py <path to font8x8_basic.h>
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = Path(sys.argv[1] if len(sys.argv) > 1 else r'C:\PMFBuild\downloads\font8x8\font8x8_basic.h').read_text()
rows = re.findall(r'\{\s*((?:0x[0-9A-Fa-f]{2},?\s*){8})\}', src)
assert len(rows) == 128, len(rows)
lines = ['; Generated by tools/make_font.py: ASCII 32-126, 8x8, from font8x8_basic.h',
         '; (Daniel Hepper, public domain; the IBM VGA glyphs). Bit 0 = leftmost pixel.',
         'DataSection', 'PM51Font:']
for code in range(32, 128):
    b = [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', rows[code])]
    lines.append('  Data.a ' + ','.join(f'${v:02X}' for v in b) + f'  ; {code}')
lines.append('EndDataSection')
for ext in ('pico', 'pico2'):
    out = ROOT / 'machine' / f'pm51_font.{ext}'
    out.parent.mkdir(exist_ok=True)
    out.write_text('\n'.join(lines) + '\n', newline='\n')
print('font written')

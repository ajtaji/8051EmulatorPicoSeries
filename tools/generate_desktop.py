# Disassembler table, from the same opcode list
# --------------------------------------------------------------------------
def dis_template(code):
    """Display template and length. Placeholders: {Dn} direct at byte n,
    {In} immediate, {Bn} bit, {Xn} /bit, {Rn} relative target, {W} 16-bit
    immediate, {L} 16-bit address, {P} 11-bit address."""
    text = g.ops[code][0]
    m, _, args = text.partition(' ')
    if m in ('AJMP', 'ACALL'):
        return f'{m} {{P}}', 2
    parts = args.split(',') if args else []
    out = []
    byte = 1
    for a in parts:
        if a == '#imm16':
            out.append('#{W}'); byte += 2
        elif a == 'addr16':
            out.append('{L}'); byte += 2
        elif a == '#imm':
            out.append(f'#{{I{byte}}}'); byte += 1
        elif a == 'dir':
            out.append(f'{{D{byte}}}'); byte += 1
        elif a == 'bit':
            out.append(f'{{B{byte}}}'); byte += 1
        elif a == '/bit':
            out.append(f'/{{B{byte}}}'); byte += 1
        elif a == 'rel':
            out.append(f'{{R{byte}}}'); byte += 1
        else:
            out.append(a)
    if code == 0x85:              # MOV dir,dir encodes the SOURCE first
        out = ['{D2}', '{D1}']
    s = m + (' ' + ','.join(out) if out else '')
    return s, byte


def build_disasm():
    out = ['; Generated by tools/generate_desktop.py from the core\'s opcode table.',
           'Global Dim M51DisText.s(256)', 'Global Dim M51DisLen.i(256)', '',
           'Procedure M51DisInit()', '  Protected i.i', '  Restore M51DisData', '  For i = 0 To 255',
           '    Read.s M51DisText(i)', '    Read.i M51DisLen(i)', '  Next', 'EndProcedure', '',
           'DataSection', 'M51DisData:']
    for code in range(256):
        if code in g.ops:
            t, n = dis_template(code)
        else:
            t, n = 'DB $A5 (undefined)', 1
        out.append(f'  Data.s "{t}"')
        out.append(f'  Data.i {n}')
    out.append('EndDataSection')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    path = ROOT / 'desktop' / 'mcs51_distable.pbi'
    path.write_text(build_disasm(), newline='\n')
    print(path)

"""Generate the desktop (PureBasic, C back end) MCS-51 core.

The instruction semantics are the same handler text tools/generate.py emits
for the Picos (it is fully parenthesised, so it means the same under
PureBasic's operator precedence as under PureMetal's). Two dispatch styles,
chosen by #M51_DISPATCH when the core is included, so they can be measured
against each other:

  #M51_DISPATCH = 1  labels-as-values: one procedure, each handler a label,
                     a 256-entry table of label addresses built in inline C,
                     each handler ending in its own `goto *table[opcode]`
  #M51_DISPATCH = 0  a 256-entry table of procedure addresses, one procedure
                     per opcode, called through a prototype from a loop

Writes desktop/mcs51_core.pbi.
"""
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate as g  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def header():
    h = g.HEADER.replace('@@TABLE_GLOBAL@@@@RESERVE@@', '')
    h = h.replace('ProcedureRAM', 'Procedure')
    h = h.replace('Global Dim M51Dispatch.Label(256)\n', 'Global Dim M51Ops.i(256)\n')
    h = h.replace("; Generated by tools/generate.py. Edit the generator, then regenerate.\n"
                  "; Intel MCS-51 (8051 / 8052) instruction-set core for PureMetal.\n"
                  "; Computed-goto dispatch through a 256-entry .Label table; the handlers and\n"
                  "; the SFR / timer / interrupt paths they call all run from SRAM.\n",
                  "; Generated by tools/generate_desktop.py. Edit the generators, then regenerate.\n"
                  "; Intel MCS-51 (8051 / 8052) instruction-set core, PureBasic (C back end).\n"
                  "; The instruction handlers are the same text as the Pico core's.\n"
                  "; #M51_DISPATCH 1: labels-as-values through inline C; 0: procedure table.\n")
    h = h.replace("; The reserved registers are application-wide.\n", "")
    return h


def c_tail(cycles):
    """The labels-as-values tail, in C."""
    return [
        'CompilerIf #M51_TIMING = 1',
        f'  ! g_m51left -= {cycles};',
        'CompilerElse',
        '  ! g_m51left -= 1;',
        'CompilerEndIf',
        '! if (g_m51left <= 0) goto ll_m51slice_done;',
        '! g_m51tmp = ((unsigned char*)a_m51code.a)[g_m51pc];',
        '! g_m51pc = (g_m51pc + 1) & 0xFFFF;',
        '! goto *m51_table[g_m51tmp];',
    ]


def body_lines(lines, tail):
    out = []
    has = False
    for l in lines:
        if l.strip() == g.TAIL:
            pad = l[:len(l) - len(l.lstrip())]
            out += [pad + t for t in tail]
            has = True
        else:
            out.append(l)
    if not has:
        out += tail
    return out


def goto_core():
    out = ['ProcedureRAM.i M51Slice(n.i)'.replace('ProcedureRAM', 'Procedure')]
    labels = ['&&ll_m51slice_illegal'] * 256
    for code in g.ops:
        labels[code] = f'&&ll_m51slice_op{code:02x}'
    out.append('  ! static void *m51_table[256] = {')
    for r in range(0, 256, 8):
        out.append('  !   ' + ', '.join(labels[r:r + 8]) + ',')
    out.append('  ! };')
    out.append('  M51Budget = n')
    out.append('  M51Left = n')
    out.append('  M51Stolen = 0')
    out.append('  ! g_m51tmp = ((unsigned char*)a_m51code.a)[g_m51pc];')
    out.append('  ! g_m51pc = (g_m51pc + 1) & 0xFFFF;')
    out.append('  ! goto *m51_table[g_m51tmp];')
    out += illegal_lines()
    for code in sorted(g.ops):
        text, cycles, lines = g.ops[code]
        out.append(f'Op{code:02X}: ; ${code:02X} {text}, {cycles} cycle{"s" if cycles > 1 else ""}')
        out += ['  ' + l for l in body_lines(lines, c_tail(cycles))]
    out += done_lines()
    return out


def illegal_lines():
    return ['Illegal:',
            '  ; $A5 is not an instruction: stop on it, uncounted, PC at the byte.',
            '  M51PC = (M51PC - 1) & $FFFF',
            '  M51BadOpcode = M51Code(M51PC)',
            '  M51Stopped = 1',
            '  Goto Done']


def done_lines():
    return ['Done:',
            '  M51Res = M51Budget - M51Stolen - M51Left',
            '  M51Cycles = M51Cycles + M51Res',
            '  M51SliceBase = M51Cycles',
            '  M51Budget = 0',
            '  M51Stolen = 0',
            '  M51Left = 0',
            '  ProcedureReturn M51Res',
            'EndProcedure']


def proc_core():
    """One procedure per opcode. A handler's tail charges its cycles and returns."""
    out = ['Prototype M51OpProto()', 'Global M51OpCall.M51OpProto', '']
    out.append('Procedure M51OpIllegal()')
    out.append('  M51PC = (M51PC - 1) & $FFFF')
    out.append('  M51BadOpcode = M51Code(M51PC)')
    out.append('  M51Stopped = 1')
    out.append('  M51Stolen = M51Stolen + M51Left')
    out.append('  M51Left = 0')
    out.append('EndProcedure')
    for code in sorted(g.ops):
        text, cycles, lines = g.ops[code]
        tail = ['CompilerIf #M51_TIMING = 1', f'  M51Left = M51Left - {cycles}', 'CompilerElse',
                '  M51Left = M51Left - 1', 'CompilerEndIf', 'ProcedureReturn']
        out.append(f'Procedure M51Op{code:02X}() ; ${code:02X} {text}, {cycles} cycle{"s" if cycles > 1 else ""}')
        out += ['  ' + l for l in body_lines(lines, tail)]
        out.append('EndProcedure')
    out.append('Procedure.i M51Slice(n.i)')
    out.append('  If M51Ready = 0')
    out.append('    For M51InitIndex = 0 To 255')
    out.append('      M51Ops(M51InitIndex) = @M51OpIllegal()')
    out.append('    Next')
    for code in sorted(g.ops):
        out.append(f'    M51Ops(${code:02X}) = @M51Op{code:02X}()')
    out.append('    M51Ready = 1')
    out.append('  EndIf')
    out.append('  M51Budget = n')
    out.append('  M51Left = n')
    out.append('  M51Stolen = 0')
    out.append('  While M51Left > 0')
    out.append('    M51OpCall = M51Ops(M51Code(M51PC))')
    out.append('    M51PC = (M51PC + 1) & $FFFF')
    out.append('    M51OpCall()')
    out.append('  Wend')
    # An illegal opcode leaves Stolen holding the budget left: keep the formula.
    out.append('  M51Res = M51Budget - M51Stolen - M51Left')
    out.append('  M51Cycles = M51Cycles + M51Res')
    out.append('  M51SliceBase = M51Cycles')
    out.append('  M51Budget = 0')
    out.append('  M51Stolen = 0')
    out.append('  M51Left = 0')
    out.append('  ProcedureReturn M51Res')
    out.append('EndProcedure')
    return out


def build():
    out = [header()]
    out.append('CompilerIf #M51_DISPATCH = 1')
    out += goto_core()
    out.append('CompilerElse')
    out += proc_core()
    out.append('CompilerEndIf')
    api = g.API.replace('ProcedureRAM', 'Procedure')
    out.append(api)
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    path = ROOT / 'desktop' / 'mcs51_core.pbi'
    path.parent.mkdir(exist_ok=True)
    text = build()
    path.write_text(text, newline='\n')
    print(path, len(text.splitlines()), 'lines')


